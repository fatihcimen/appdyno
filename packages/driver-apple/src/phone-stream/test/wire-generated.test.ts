import { describe, expect, it, vi } from 'vitest';
import { readBplist } from '../../webinspector.js';
import { dtxFrame, DtxReader } from '../dtx.js';
import type { TcpConnection } from '../ipstack.js';
import { archive, unarchive } from '../keyed-archive.js';
import { RemoteXpc } from '../remotexpc.js';
import { decodeObject, encodeObject, encodeWrapper, XpcInt64 } from '../xpc-codec.js';

/** The same bytes each run, from any seed: one that fails is one to read. */
function generator(seed: number) {
  let s = seed;
  return (n: number) => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    s >>>= 0;
    return s % n;
  };
}

type Next = ReturnType<typeof generator>;

/** A real message with some of it spoilt: a length at its extremes, a byte flipped, or its end cut off. */
function spoilt(whole: Buffer, next: Next) {
  const b = Buffer.from(whole);
  for (let i = next(4); i >= 0; i--) {
    const at = next(b.length);
    const put = next(4);
    if (put === 0 && at + 4 <= b.length) b.writeUInt32LE(0xffffffff, at);
    else if (put === 1 && at + 4 <= b.length) b.writeUInt32LE(0, at);
    else b[at] = next(256);
  }
  return next(3) ? b : b.subarray(0, next(b.length));
}

const value = {
  name: 'Form',
  list: ['a', 1, { deep: ['b', { deeper: Buffer.from([1, 2, 3]) }] }],
  on: true,
  none: null,
};

/** What must never happen is a hang or anything but an error: every run here ends, as a test's limit says. */
const ends = (read: () => unknown) => {
  try {
    read();
  } catch (e) {
    expect(e).toBeInstanceOf(Error);
  }
};

describe('generated bytes, on each reader of a phone', () => {
  const ROUNDS = 1_500;

  it('an XPC object', () => {
    const next = generator(1);
    const whole = encodeObject({ ...value, id: new XpcInt64(-1) });
    for (let i = 0; i < ROUNDS; i++) ends(() => decodeObject(spoilt(whole, next)));
  });

  it('a keyed archive, and the plist under it', () => {
    const next = generator(2);
    const whole = archive(value);
    for (let i = 0; i < ROUNDS; i++) {
      const b = spoilt(whole, next);
      ends(() => unarchive(b));
      ends(() => readBplist(b));
    }
  });

  it('DTX frames, cut anywhere', () => {
    const next = generator(3);
    const whole = Buffer.concat([dtxFrame(1, 'a:', [value], true), dtxFrame(2, 'b', [], false)]);
    for (let i = 0; i < ROUNDS; i++) {
      const reader = new DtxReader();
      const b = spoilt(whole, next);
      const cut = next(b.length + 1);
      ends(() => [reader.push(b.subarray(0, cut)), reader.push(b.subarray(cut))]);
    }
  });

  it('a service connection, frame by frame', () => {
    const next = generator(4);
    const message = encodeWrapper(0x101, value as never);
    for (let i = 0; i < ROUNDS; i++) {
      let data: (d: Buffer) => void = () => undefined;
      const connection = {
        write: vi.fn(),
        onData: (l: typeof data) => (data = l),
        onClose: vi.fn(),
        close: vi.fn(),
      } as unknown as TcpConnection;
      RemoteXpc.start(connection);
      const body = spoilt(message, next);
      const head = Buffer.alloc(9);
      head.writeUIntBE(body.length, 0, 3);
      head.writeUInt32BE([1, 3, 5][next(3)]!, 5);
      ends(() => data(Buffer.concat([head, body])));
    }
  });
});
